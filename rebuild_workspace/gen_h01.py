#define VAULT_SBOX (VAULT_HDR)
#define VAULT_K    (VAULT_HDR + 256)
#define VAULT_T    (VAULT_HDR + 256 + PASS_LEN)
#define VAULT_N    (VAULT_HDR + 256 + PASS_LEN * 2)

